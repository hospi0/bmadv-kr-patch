def main():
    lines = [HEAD]
    for x, y, w, h, font, kern, ja, ko in ROWS:
        lines.append("\t".join([str(x), str(y), str(w), str(h), font, "m", "1", "1",
                                kern, "", "", "c", "1", "1", "0", "t", ja, ko]))
