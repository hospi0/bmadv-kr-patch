HEAD = "x	y	w	h	font	align	xscale	yscale	kern	dx	dy	mode	ja	ko"




def main():
    """--d2 를 주면 디스크 2 표지판을 짓는다(원본·출력 경로가 다르다)."""
    disc = 2 if "--d2" in sys.argv else 1
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    table = SIGNS_D2 if disc == 2 else SIGNS
    src = os.path.join(ROOT, "work", "disc%d" % disc, "EVENT.DAT_EXT")
    only = [int(v) for v in args] or sorted(table)
    os.makedirs(OUT, exist_ok=True)
    for n in only:
        rows = [HEAD]
        two = len(table[n]) == 2
        for i, (x, y, w, h, ja, ko) in enumerate(table[n]):
            # ★두 줄짜리는 원문 가나가 커서 줄 간격이 넓다. 한글(22px)은
            #   그대로 두면 두 줄이 붙어 보이므로 위·아래로 2px 벌린다.
            dy = 0 if not two else (-2 if i == 0 else 2)
            rows.append("	".join([str(x), str(y), str(w), str(h),
                                   "n", "m", "2", "2", "", "", str(dy), "t", ja, ko]))
        p = os.path.join(TSV, "ui_d%dsign%03d.tsv" % (disc, n))
        open(p, "w", encoding="utf-8").write("\n".join(rows) + "\n")
        name = ("d2_event%03d_ko.png" % n) if disc == 2 else ("event%03d_ko.png" % n)
        print("== D%d %03d" % (disc, n))
        subprocess.check_call([sys.executable,
                               os.path.join(ROOT, "tools", "ui_render.py"),
                               os.path.join(src, "%03d.png" % n), p,
                               os.path.join(OUT, name)])


if __name__ == "__main__":
    main()
