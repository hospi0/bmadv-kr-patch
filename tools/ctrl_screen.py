"""조작설명 화면(EVENT 058·060·062·064·615·677·699·729 …) 스크램블 해제.

★★ 규칙 (2026-08-18, 정답 스크린샷 대조로 실증. NCC 0.95~0.99)

1. 텍스처 256×256 은 **16행짜리 띠 16장**이다. 띠들은 세로로 섞인 게 아니라
   **가로로 한 줄로 이어진다** — 띠0 의 오른끝이 띠1 의 왼끝. 즉 원본은
   **16행 × 4096픽셀짜리 «스트림»**.
      st = concat([tex[16i:16i+16] for i in range(16)], axis=1)

2. 화면에 그릴 때 **가로는 1:1, 세로는 2배**로 늘린다(16행 → 32행).
   ⚠️ 세로 2배를 모르면 어떤 대조도 NCC 0.6 을 못 넘는다. 글자 피치는
   텍스처 25px = 화면 25px 로 가로만 1:1 이다.

3. 화면 y 는 **항상 32의 배수**(밴드). 화면은 640×480 = 15밴드.

4. 스트림은 **연속된 구간(run)들로 잘려** 밴드에 차례로 붙는다.
   각 run 은 한 밴드의 «내용이 있는 가로 구간»이고, 밴드는 위에서 아래로 진행한다.
   ⚠️ 구간 경계는 텍스처마다 다르다 — 화면마다 글자 길이가 달라서 그렇다.
      한 화면의 배치는 그 화면 스크린샷 한 장이면 자동으로 복원된다(recover()).

⛔ 폐기된 가설: 「448 폭으로 접기」. 윗줄 3개만 우연히 맞았고, 띠가 밴드
   경계를 넘어가 패드 그림 조각이 엉뚱한 줄에 붙는다.
"""
import numpy as np
from PIL import Image

# 064「料理」조작설명에서 실측한 배치 (스트림시작, 길이, 밴드k, 화면x)
SEGS_064 = [
    (176, 544, 1, 64), (720, 448, 2, 160), (1168, 144, 3, 176),
    (1312, 288, 4, 96), (1600, 144, 4, 400), (1744, 272, 5, 96),
    (2016, 144, 5, 400), (2160, 448, 6, 96), (2608, 256, 7, 96),
    (2864, 256, 7, 384), (3120, 288, 8, 304), (3408, 112, 9, 80),
    (3520, 432, 9, 208), (3952, 144, 10, 64),
]


def stream(png, resample=Image.NEAREST):
    """텍스처 → 16×4096 스트림 → 세로 2배(32×4096)."""
    t = np.asarray(Image.open(png).convert("RGB"))
    st = np.concatenate([t[i * 16:(i + 1) * 16] for i in range(16)], axis=1)
    return np.asarray(Image.fromarray(st).resize((4096, 32), resample))


def compose(png, segs=SEGS_064):
    """배치표대로 640×480 화면을 되조립."""
    st2 = stream(png)
    out = np.zeros((480, 640, 3), np.uint8)
    for p, L, k, x in segs:
        out[k * 32:k * 32 + 32, x:x + L] = st2[:, p:p + L]
    return out
