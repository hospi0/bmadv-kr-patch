def control(name, color, labels, rows, sents, boxes, extra=()):
    """조작설명 — boxes = 지울 상자(검정), labels = [(글 조각 목록)] 단추 설명(rows = 각 줄 가운데 y, 선 끝 오른쪽 x), sents = [('hseq' 조각, (x, y))]"""
    dark, bright = NEON[color]; lx, ys = rows
    ops = [('fill', b, (0, 0, 0)) for b in boxes]
    ops.append(('h', '「%s」' % name, (196, 64), 'gothic', 50, WH, dict(anchor='mm', stroke=(2, bright), glow=(5, dark))))
    ops.append(('h', '조작 설명', (300 + max(0, len(name) - 2) * 26, 68), 'gothic', 30, WH, dict(anchor='lm', shadow=(2, 2, (60, 60, 60)))))
    for lab, y in zip(labels, ys): ops.append(('hseq', lab, (lx, y), 'gothic', 24, {}))
    for seq, xy in sents: ops.append(('hseq', seq, xy, 'gothic', 23, {}))
    return ops + list(extra)


